/**
 * Helper to get question in the requested language.
 * Preserves the exact ID, subjectId, chapterId, difficulty, correctOptionIndex (0-3), and formula list!
 */
export function getLocalizedQuestion(q: Question, lang: SupportedLanguage): Question {
  if (lang === 'en') return q;

  const translation = QUESTION_TRANSLATIONS[q.id]?.[lang] || q.translations?.[lang];
  if (!translation) {
    return {
      ...q,
      questionText: `${q.questionText} [${lang === 'gu' ? 'અનુવાદ ટૂંક સમયમાં ઉમેરાશે' : 'अनुवाद शीघ्र उपलब्ध होगा'}]`
    };
  }

  return {
    ...q,
    questionText: translation.questionText,
    options: translation.options,
    explanation: translation.explanation,
    stepByStepSolution: translation.stepByStepSolution,
    conceptTakeaway: translation.conceptTakeaway
  };
}
